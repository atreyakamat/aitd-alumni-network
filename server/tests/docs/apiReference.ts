/**
 * Builds docs/API_REFERENCE.md from the live Express router, so the endpoint
 * list and each route's access level can never drift from the code.
 *
 * Regenerate with `npm run docs:api` (from server/).
 */
import type { Router } from 'express';
import { authenticate, isAdmin, isChapterAdmin, isSuperAdmin, optionalAuth } from '../../src/middleware/auth';

export type AccessLevel = 'public' | 'optional' | 'auth' | 'chapterAdmin' | 'admin' | 'superAdmin';

export interface RouteDoc {
  method: string;
  path: string;
  access: AccessLevel;
  validated: boolean;
}

const ACCESS_LABEL: Record<AccessLevel, string> = {
  public: 'Public',
  optional: 'Public (personalised when signed in)',
  auth: 'Signed in',
  chapterAdmin: 'Chapter admin+',
  admin: 'Admin+',
  superAdmin: 'Super admin',
};

const METHOD_ORDER = ['get', 'post', 'put', 'patch', 'delete'];

const accessOf = (handlers: unknown[]): AccessLevel => {
  if (handlers.includes(isSuperAdmin)) return 'superAdmin';
  if (handlers.includes(isAdmin)) return 'admin';
  if (handlers.includes(isChapterAdmin)) return 'chapterAdmin';
  if (handlers.includes(authenticate)) return 'auth';
  if (handlers.includes(optionalAuth)) return 'optional';
  return 'public';
};

/** Every route registered on the API router, in registration order. */
export const collectRoutes = (router: Router): RouteDoc[] =>
  (router as any).stack
    .filter((layer: any) => layer.route)
    .flatMap((layer: any) => {
      const handlers = layer.route.stack.map((s: any) => s.handle);
      const names = layer.route.stack.map((s: any) => s.name as string);
      return Object.keys(layer.route.methods).map((method) => ({
        method,
        path: layer.route.path as string,
        access: accessOf(handlers),
        validated: names.includes('validateRequest'),
      }));
    });

const sectionOf = (path: string) => path.split('/')[1] || 'root';

const title = (section: string) =>
  section.split('-').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');

export const renderApiReference = (routes: RouteDoc[]): string => {
  const sections = new Map<string, RouteDoc[]>();
  for (const route of routes) {
    const key = sectionOf(route.path);
    sections.set(key, [...(sections.get(key) ?? []), route]);
  }

  const counts = routes.reduce<Record<string, number>>((acc, r) => ({ ...acc, [r.access]: (acc[r.access] ?? 0) + 1 }), {});

  const lines: string[] = [
    '# API Reference',
    '',
    '<!-- Generated by `npm run docs:api` in server/ from the live router. Do not edit by hand;',
    '     tests/docs/api-reference.test.ts fails when this file is out of date. -->',
    '',
    `Base path: \`/api\` (for example \`https://<api-host>/api/auth/login\`). ${routes.length} endpoints.`,
    '',
    'Responses use the envelope `{ "success": true, "data": ..., "pagination"?: {...} }`, and errors use',
    '`{ "success": false, "error": { "message": "...", "code": "..." } }`. Send authenticated requests with',
    '`Authorization: Bearer <accessToken>`. Access tokens last 15 minutes; renew them with `POST /auth/refresh-token`.',
    '',
    '## Access levels',
    '',
    '| Level | Meaning | Endpoints |',
    '|---|---|---|',
    ...(['public', 'optional', 'auth', 'chapterAdmin', 'admin', 'superAdmin'] as AccessLevel[]).map(
      (level) => `| ${ACCESS_LABEL[level]} | ${
        {
          public: 'No token needed',
          optional: 'Works anonymously; returns more (for example members-only items) with a token',
          auth: 'Any active, signed-in user. Ownership rules are enforced per resource',
          chapterAdmin: 'CHAPTER_ADMIN, ADMIN or SUPER_ADMIN. Chapter admins are limited to their own chapter',
          admin: 'ADMIN or SUPER_ADMIN',
          superAdmin: 'SUPER_ADMIN only',
        }[level]
      } | ${counts[level] ?? 0} |`,
    ),
    '',
    'Role checks re-read the user from the database on every request, so role changes and deactivation apply immediately.',
    'Auth endpoints (login, register, password reset, 2FA, email verification, OAuth exchange) are limited to',
    '10 requests per 15 minutes per IP; refresh-token to 60; every other `/api` route shares a 300 request budget.',
    '',
    '"Validated" means the request body or query is schema-validated before the handler runs (invalid input returns 400).',
    '',
  ];

  for (const [section, sectionRoutes] of sections) {
    lines.push(`## ${title(section)}`, '', '| Method | Path | Access | Validated |', '|---|---|---|---|');
    const sorted = [...sectionRoutes].sort(
      (a, b) => a.path.localeCompare(b.path) || METHOD_ORDER.indexOf(a.method) - METHOD_ORDER.indexOf(b.method),
    );
    for (const r of sorted) {
      lines.push(`| ${r.method.toUpperCase()} | \`${r.path}\` | ${ACCESS_LABEL[r.access]} | ${r.validated ? 'Yes' : ''} |`);
    }
    lines.push('');
  }

  return lines.join('\n');
};
