#!/usr/bin/env bash
# One-command setup for AIEM Connect.
#
#   ./start.sh
#
# On first run this generates a .env with secure random secrets (including the admin
# password), then builds and starts the whole stack with Docker Compose. Re-running it
# just rebuilds/restarts and keeps your data and secrets.
set -euo pipefail
cd "$(dirname "$0")"

green() { printf '\033[32m%s\033[0m\n' "$1"; }
yellow() { printf '\033[33m%s\033[0m\n' "$1"; }

# --- preflight --------------------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
  echo "Docker is required. Install Docker Desktop / Engine, then re-run ./start.sh" >&2
  exit 1
fi
if ! docker compose version >/dev/null 2>&1; then
  echo "This needs Docker Compose v2 (the 'docker compose' command)." >&2
  exit 1
fi

# --- random secret helper ---------------------------------------------------
gen() {
  local out=""
  if command -v node >/dev/null 2>&1; then
    # A node that is on the PATH but cannot run (an unselected nvm version) must not stop the setup: use the fallback below.
    out="$(node -e "console.log(require('crypto').randomBytes(36).toString('base64url'))" 2>/dev/null || true)"
  fi
  if [ -z "$out" ]; then
    # base64url-safe output (no / + = @ : so it's safe in URLs and .env). A fixed chunk is read first and nothing closes
    # a pipe early: with `set -o pipefail` a SIGPIPE from `head` would abort the whole script.
    out="$(LC_ALL=C tr -dc 'A-Za-z0-9_-' < <(head -c 4096 /dev/urandom) | cut -c1-48)"
  fi
  printf '%s\n' "$out"
}

# --- generate .env on first run ---------------------------------------------
if [ ! -f .env ]; then
  yellow "No .env found — generating one with secure random secrets…"
  ADMIN_PASSWORD="$(gen | cut -c1-16)Aa1!"   # guarantees upper/lower/digit/symbol + length
  cat > .env <<EOF
# Auto-generated by start.sh. Keep this file private; back up the secrets below.
POSTGRES_DB=aiem_connect
POSTGRES_USER=aiem
POSTGRES_PASSWORD=$(gen)

JWT_SECRET=$(gen)
JWT_REFRESH_SECRET=$(gen)

SEED_ON_START=true
SEED_ADMIN_EMAIL=admin@aiemgoa.ac.in
SEED_ADMIN_PASSWORD=$ADMIN_PASSWORD
# Set to true to also load demo users/events/news (not for production):
SEED_SAMPLE_DATA=false

FRONTEND_URL=http://localhost:3000
CORS_ORIGINS=http://localhost:3000,http://localhost
NEXT_PUBLIC_API_URL=http://localhost:5000/api

# --- LOCAL TRIAL ONLY ---------------------------------------------------------------------
# The API runs in production mode and refuses to start on a configuration meant for the public internet
# (https addresses, a mail server, ...). These two lines let this stack run on ONE machine with neither.
# For a real deployment REMOVE THEM, set real values, and follow docs/PRODUCTION_CHECKLIST.md
# (check with:  npm run preflight -w server -- --env-file ../.env).
ALLOW_INSECURE_PRODUCTION_CONFIG=true
REQUIRE_EMAIL_VERIFICATION=false
EOF
  chmod 600 .env
  green "Created .env."
  echo "  Admin login once it's up:  admin@aiemgoa.ac.in  /  ${ADMIN_PASSWORD}"
  echo "  (also stored in .env as SEED_ADMIN_PASSWORD)"
  echo
fi

# --- build + start ----------------------------------------------------------
yellow "Building and starting the stack (first run pulls images + builds — this can take several minutes)…"
docker compose up -d --build

# --- wait for the web container to report healthy ---------------------------
echo
yellow "Waiting for services to become healthy…"
deadline=$(( $(date +%s) + 300 ))
poll="${START_POLL_SECONDS:-5}"
while :; do
  # A container that has stopped will not become healthy: say why now, not after five minutes
  api_run="$(docker compose ps api --format '{{.State}}' 2>/dev/null || echo '')"
  case "$api_run" in
    exited|dead|restarting)
      echo
      yellow "The API container is not staying up ($api_run). Its last log lines:"
      docker compose logs --tail 30 api 2>&1 || true
      echo
      echo "A production configuration problem is the usual cause: see docs/PRODUCTION_CHECKLIST.md" >&2
      exit 1
      ;;
  esac
  web_state="$(docker compose ps web --format '{{.Health}}' 2>/dev/null || echo '')"
  api_state="$(docker compose ps api --format '{{.Health}}' 2>/dev/null || echo '')"
  if [ "$web_state" = "healthy" ] && [ "$api_state" = "healthy" ]; then
    break
  fi
  if [ "$(date +%s)" -ge "$deadline" ]; then
    yellow "Still starting after 5 min. Check logs with:  docker compose logs -f"
    break
  fi
  sleep "$poll"
done

echo
green "AIEM Connect is up."
echo "  Web:  http://localhost:3000"
echo "  API:  http://localhost:5000/health"
echo "  Admin login is in your .env (SEED_ADMIN_EMAIL / SEED_ADMIN_PASSWORD)."
echo
echo "  Logs:   docker compose logs -f"
echo "  Stop:   docker compose down        (keeps data)"
echo "  Reset:  docker compose down -v     (deletes data)"
