// Builds the .env for the verification stack: random secrets, URLs derived from the host name. TEST ONLY: the stack it
// configures runs in "insecure production" mode with a mail catcher (docker-compose.test.yml).
import crypto from 'node:crypto';

export const ADMIN_EMAIL = 'verify-admin@aiem.test';

export const makeEnv = ({
  host = 'localhost',
  proxyPort = 80,
  webPort = 3000,
  apiPort = 5000,
  postgresPort = 5432,
  mailpitPort = 8025,
  randomBytes = crypto.randomBytes,
} = {}) => {
  const secret = (bytes) => randomBytes(bytes).toString('base64url');
  const origin = Number(proxyPort) === 80 ? `http://${host}` : `http://${host}:${proxyPort}`;
  const adminPassword = `${secret(12)}Aa1!`; // 12+ characters with every class, as the password policy requires

  const values = {
    POSTGRES_DB: 'aiem_verify',
    POSTGRES_USER: 'aiem',
    POSTGRES_PASSWORD: secret(24),
    JWT_SECRET: secret(36),
    JWT_REFRESH_SECRET: secret(36),
    SEED_ON_START: 'true',
    SEED_ADMIN_EMAIL: ADMIN_EMAIL,
    SEED_ADMIN_PASSWORD: adminPassword,
    SEED_SAMPLE_DATA: 'false',
    FRONTEND_URL: origin,
    CORS_ORIGINS: `${origin},http://localhost,http://127.0.0.1`,
    // The web image bakes this in at build time: the address a browser uses to reach the API (single origin through nginx)
    NEXT_PUBLIC_API_URL: `${origin}/api`,
    TRUST_PROXY: '1',
    KAFKA_TOPIC_PREFIX: 'aiem',
    KAFKA_PARTITIONS: '3',
    PROXY_HOST_PORT: String(proxyPort),
    WEB_HOST_PORT: String(webPort),
    API_HOST_PORT: String(apiPort),
    POSTGRES_HOST_PORT: String(postgresPort),
    MAILPIT_UI_PORT: String(mailpitPort),
  };

  const text =
    '# Generated by scripts/docker-verify (TEST ONLY: never reuse these values or this file for a real deployment)\n' +
    Object.entries(values)
      .map(([key, value]) => `${key}=${value}`)
      .join('\n') +
    '\n';

  return {
    text,
    values,
    origin,
    adminEmail: ADMIN_EMAIL,
    adminPassword,
    /** Values that must never appear in a log or in the evidence bundle. */
    secrets: [values.POSTGRES_PASSWORD, values.JWT_SECRET, values.JWT_REFRESH_SECRET, adminPassword],
  };
};
